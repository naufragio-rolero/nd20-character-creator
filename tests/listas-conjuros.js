'use strict';
/* Listas de Conjuros: contrato documental y regresión sin reglas de suplementos. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>JSON.parse(fs.readFileSync(path.join(__dirname,'..',p),'utf8'));
const a=require('../assets/spell-lists.js');
const drs=read('data/conjuros-drs-fichas.json');
const poderes=read('data/catalogo-poderes.json');
const propuesta=read('data/listas-conjuros-borradores.json');
const progresiones=read('data/progresiones-oficiales.json');
const c=a.crearCatalogo(drs,poderes);
const b=a.leerBorradores(propuesta,c);
const ident='usuario:12345678';
assert.equal(drs.version_drs,'1.1.12');
assert.equal(c.conjuros.length,64);
assert.equal(poderes.conjuros.length,433,'Catálogo general ajeno al alcance: no se elimina ni amplía');
assert.equal(c.oficiales.length,2);
assert.equal(c.porId.get('conjuro-20').escuela,'Divina','Silencio sigue siendo Divina');
assert.ok(c.porId.get('conjuro-20').listas_oficiales.includes('Mago'));
assert.ok(c.porId.get('conjuro-32').circulo===4);
assert.match(drs.observaciones_editoriales[0],/Contrato de fraternidad/);
assert.ok(!c.porId.has('conjuro-199'),'Nunca importar Tomo de Magia');
assert.ok(c.conjuros.every(s=>s.texto_normativo&&s.efectos&&s.fuente.includes('DRS')));
const proteger=JSON.stringify(c.oficiales);
const origen=c.oficiales.find(x=>x.id==='drs:Mago');
const clero=c.oficiales.find(x=>x.id==='drs:Clérigo');
assert.ok(origen.conjuros.includes('conjuro-20'),'Silencio pertenece a la lista Mago');
assert.ok(clero.conjuros.includes('conjuro-20'),'Silencio pertenece a Clérigo');
let lib=a.vacia(c);
const nueva={id:ident,nombre:'Prueba Centinela',descripcion:'Lista sin textos duplicados.',
  maxCirculo:4,conjuros:['conjuro-5','conjuro-20','conjuro-38']};
lib=a.guardarLista(lib,nueva,c,b);
assert.equal(lib.listas[0].conjuros.length,3);
assert.ok(!JSON.stringify(lib).includes('Transformas a una criatura viva'));
assert.deepEqual(c.oficiales,JSON.parse(proteger),'Una edición no altera listas oficiales');
lib=a.guardarLista(lib,Object.assign({},nueva,{nombre:'Prueba editada',conjuros:['conjuro-5']}),c,b);
assert.equal(lib.listas.length,1,'Editar no crea una copia');
assert.equal(lib.listas[0].nombre,'Prueba editada');
assert.equal(lib.listas[0].conjuros.length,1,'Se pueden retirar Conjuros');
assert.throws(()=>a.guardarLista(lib,Object.assign({},nueva,{id:'drs:Mago'}),c,b),/identificador|personal/i);
assert.throws(()=>a.guardarLista(lib,Object.assign({},nueva,{conjuros:['conjuro-5','conjuro-5']}),c,b),/repetido/);
assert.throws(()=>a.guardarLista(lib,Object.assign({},nueva,{conjuros:['conjuro-45']}),c,b),/Círculo máximo/);
assert.throws(()=>a.guardarLista(lib,Object.assign({},nueva,{conjuros:['conjuro-199']}),c,b),/ajeno al DRS/);
assert.throws(()=>a.guardarLista(lib,Object.assign({},nueva,{conjuros:['fantasma']}),c,b),/desconocido/);
const idCopia='usuario:abcdef12345678';
lib=a.duplicarLista(lib,'drs:Mago',idCopia,'Mi Mago',c,b);
assert.equal(lib.listas.length,2);
assert.deepEqual(lib.listas[1].conjuros,origen.conjuros);
assert.equal(lib.listas[1].maxCirculo,8);
assert.deepEqual(c.oficiales,JSON.parse(proteger),'Duplicar tampoco modifica el DRS');
assert.equal(b.listas.length,1,'Solo un borrador Centinela');
assert.equal(b.listas[0].conjuros.length,9);
assert.equal(b.listas[0].maxCirculo,4);
assert.equal(b.progresiones[0].niveles.length,30);
lib=a.vincular(lib,'Centinela','propuesta:centinela-v5','propuesta:centinela-v5',c,b);
let v=a.resolver(lib,'Centinela',1,c,b,progresiones);
assert.deepEqual(v.espacios,[0,0,0,0,0,0,0,0]);
assert.equal(v.disponibles.length,0);
v=a.resolver(lib,'Centinela',2,c,b,progresiones);
assert.deepEqual(v.espacios.slice(0,4),[2,0,0,0]);
assert.equal(v.disponibles.length,3);
v=a.resolver(lib,'Centinela',7,c,b,progresiones);
assert.deepEqual(v.espacios.slice(0,4),[3,2,2,1]);
assert.equal(v.disponibles.length,9);
v=a.resolver(lib,'Centinela',30,c,b,progresiones);
assert.deepEqual(v.espacios.slice(0,4),[4,4,4,4]);
assert.equal(v.espacios.slice(4).reduce((n,x)=>n+x,0),0);
lib=a.vincular(lib,'Profeta',idCopia,null,c,b);
v=a.resolver(lib,'Profeta',12,c,b,progresiones);
assert.equal(v.espacios,null,'Sin progresión no hay Espacios inventados');
assert.equal(v.disponibles.length,0);
assert.ok(v.repertorio.length>0,'La lista sigue definiendo acceso sin afirmar lanzamientos');
assert.throws(()=>a.vincular(lib,'Profeta','conjuro-20',null,c,b),/inexistente/);
assert.throws(()=>a.vincular(lib,'Profeta','drs:Mago','inventada',c,b),/documentada/);
assert.throws(()=>a.eliminarLista(lib,idCopia,c,b),/Desvincula primero/);
const exp=a.exportar(lib,c,b);
const copia=a.importar(exp,c,b);
assert.deepEqual(copia,lib,'Exportación e importación de ida y vuelta');
assert.ok(!exp.includes('Generas una grieta'),'La exportación no duplica texto normativo');
assert.throws(()=>a.importar(exp.replace('1.1.12','1.1.11'),c,b),/versión del DRS distinta/);
assert.throws(()=>a.importar('{"esquema":"naufragio.repertorios/v1"}',c,b),/incompatible/);
assert.throws(()=>a.importar('{"esquema":',c,b),SyntaxError);
assert.throws(()=>a.importar(JSON.stringify({...lib,asociaciones:[...lib.asociaciones,lib.asociaciones[0]]}),c,b),/más de una vez/);
lib=a.desvincular(lib,'Profeta',c,b);
lib=a.eliminarLista(lib,idCopia,c,b);
assert.equal(lib.listas.length,1);
assert.equal(a.importar(a.exportar(lib,c,b),c,b).listas.length,1);
const html=fs.readFileSync(path.join(__dirname,'..','listas-de-conjuros.html'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'..','assets/spell-lists-ui.js'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'..','assets/spell-lists.css'),'utf8');
assert.match(html,/<html lang="es">/);
assert.match(html,/aria-live="polite"/);
assert.match(html,/filtro-escuela/);
assert.match(html,/asoc-progresion/);
assert.match(ui,/textContent/);
assert.match(css,/@media\(max-width:760px\)/);
assert.deepEqual(c.oficiales,JSON.parse(proteger));
console.log('OK · listas DRS, selección, edición, duplicación, validaciones, Centro de Hyrule, Ocupaciones e importación/exportación.');
